import type { DesireTier } from '../contract/types.ts';

export interface PrologueOptionSpec {
  /** 按钮文字（玩家点选前看到的） */
  text: string;
  /** 选中后**立即**显示的那一段（档 A 不调 LLM ⇒ 它是"结果"的唯一载体） */
  resultText: string;
}

export interface PrologueCardSpec {
  /** 1~10，**呈现顺序**（第 1 天 5 条 = ①~⑤，第 2 天 5 条 = ⑥~⑩） */
  seq: number;
  /** 序幕第几天（**界面恒显示「Day 0」**，这个值只用于编排与断言） */
  day: 1 | 2;
  title: string;
  /** **账本地点名**（→ `loc` id 由 `turn/prologue.ts` 按名解析；解析不到会刺眼地记警告） */
  place: string;
  /** 显示用地点；缺省 = `place` */
  stage?: string;
  /** 场面正文（档 A 的 `content`） */
  scene: string;
  options: readonly PrologueOptionSpec[];
  /** 「并入概要」的一句；**末条恒 `''`**（不计入） */
  summary: string;
  /** 末条：点下即触发 `opening`（全局 1 次） */
  opening?: true;
}

