/**
 * 序幕用掉的**最大**事件号（**10** —— 各条保留原号，`e5` 是永不使用的空号）。
 * ⚠️ 水位与"正文第一条生成事件"都由它钉住：`initialWatermark` 订 `e1`~`e10`，
 * 正文第一条生成事件恒从 **`e11`** 起，与删卡无关。
 */
export const PROLOGUE_MAX_SEQ = Math.max(...PROLOGUE_CARDS.map((c) => c.seq));

/** 序幕第 1 天有几条（**4**）—— 用来把 9 条分成「第 1 天 / 第 2 天」两组 */
export const PROLOGUE_DAY1_COUNT = PROLOGUE_CARDS.filter((c) => c.day === 1).length;

/** 序幕结束时由规则层并进「已处理概要」的**固定概要句数**（8 —— 末条不计入） */
export function prologueSummaryLines(): string[] {
  return PROLOGUE_CARDS.filter((c) => c.summary !== '').map((c) => c.summary);
}

/**
 * 序幕事件的 id —— `e1`~`e10`（顺序 = `seq`）。
 * ⚠️ 正文第一条**生成**的事件因此从 `e11` 起（顺位分配：单调递增、永不复用）。
 */
export function prologueEventId(seq: number): string {
  return 'e' + seq;
}

const PROLOGUE_IDS: readonly string[] = PROLOGUE_CARDS.map((c) => prologueEventId(c.seq));

/** 这个 id 是不是序幕那 10 条之一（用集合而不是正则：`e10` 与 `e1` 靠正则容易糊） */
export function isPrologueEventId(id: string): boolean {
  return PROLOGUE_IDS.includes(id);
}

/**
 * 这个 id 是序幕的**第几条**（`1`~`10`；不是序幕 ⇒ `null`）。
 *
 * ⚠️ 为什么不用 `Number(id.slice(1))`：那对 `e1` 与 `e10` 都能算出数，但对一个**恰好叫 `e7`
 *    的正文事件**也会算出 7 —— 顺位水位虽然保证不会重号，但"能算"不等于"是"。
 *    这里走的是与 `isPrologueEventId` 同一张表，**两个判断同源**。
 * ⚠️ 一次只呈现一条（见 `turn/prologue.ts·advancePrologue`）：推进顺序全靠它。
 */
export function prologueSeqOf(id: string): number | null {
  const c = PROLOGUE_CARDS.find((x) => prologueEventId(x.seq) === id);
  return c ? c.seq : null;
}

/** 第 `seq` 条文案（越界 ⇒ `null`） */
export function prologueCardOf(seq: number): PrologueCardSpec | null {
  return PROLOGUE_CARDS.find((c) => c.seq === seq) ?? null;
}

/** 末条的 id —— 点下它即触发 `opening`，随后进入第 1 天（取**末条**的 seq，不取条数） */
export const PROLOGUE_OPENING_ID = prologueEventId(PROLOGUE_CARDS[PROLOGUE_CARDS.length - 1].seq);
