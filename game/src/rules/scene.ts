// ⚠️ **一份权威拷贝**：轮次上限同时被三处消费 ——
//    · `prompt/blocks.ts` 渲染【此刻是】的"（上限 N）"（给模型看）；
//    · `turn/scene.ts` 的状态机据此**强制截断**（真正管用的一道）；
//    · 单测据此断言两者口径一致。
//    ⇒ 别在任何一处另写一个字面量 `7`（与 `FREE_EVENT_CAP` 同一条纪律：
//      「供指令正文与单测共用一份，避免两处各写一个数」）。

/**
 * 一个场景最多推进多少轮。
 *
 * 《规则.md》§二 路径⑤：「**轮次上限 7**，玩家随时可退出」。
 * ⚠️ 与之相伴的成本上界（同节）：每轮 1~2 次调用 ⇒ **上界 2n / 下界 n**，即 **7 ~ 14 次**。
 *    这是全局最贵的一处 —— 所以"减少需要判定的轮数"才是真杠杆。
 */
export const SCENE_ROUND_CAP = 7;

/**
 * 场景为什么结束。
 *
 * ⚠️ 它同时决定【场景经过】要不要写得详细：`轮数用尽` 往往意味着"话说了一半"，
 *    收尾的 `summary` 是唯一能把这半截话记下来的地方。
 */
export const SCENE_END_REASONS = ['玩家主动退出', '轮数用尽', '已自然收束'] as const;
export type SceneEndReason = (typeof SCENE_END_REASONS)[number];
