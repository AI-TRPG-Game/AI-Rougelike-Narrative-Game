/**
 * 一个场景最多推进多少轮。
 *
 * 《规则.md》§二 路径⑤：「轮次上限…，玩家随时可退出」。
 * ⚠️ **2026-10-08 用户裁定：7 轮实测太少 ⇒ 改 10**（原话「经过实测，最大轮数 7 轮太少，
 *    我们改成 10 轮，其余逻辑不变」）。
 * ⚠️ 与之相伴的成本上界：每轮恒 1 次叙事调用（2026-10-07 起不掷骰）＋ 手动收尾 0~1 次
 *    ⇒ 整场 **n ~ n+1 次**（10 轮即 10 ~ 11 次）。这是全局最贵的一处。
 */
export const SCENE_ROUND_CAP = 10;

/**
 * 场景为什么结束。
 *
 * ⚠️ 它同时决定【场景经过】要不要写得详细：`轮数用尽` 往往意味着"话说了一半"，
 *    收尾的 `summary` 是唯一能把这半截话记下来的地方。
 */
export const SCENE_END_REASONS = ['玩家主动退出', '轮数用尽', '已自然收束'] as const;
export type SceneEndReason = (typeof SCENE_END_REASONS)[number];
